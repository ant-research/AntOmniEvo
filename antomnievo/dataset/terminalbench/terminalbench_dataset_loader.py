import json
import logging
import os
import random

from antomnievo.dataset.terminalbench.terminalbench_data_inst import TerminalBenchDataInst

logger = logging.getLogger(__name__)

# Entries under `terminalbench2/dataset/` that are NOT tasks (helper artifacts,
# HuggingFace-style dumps, summary files, etc.). Anything matching an entry
# here is skipped by the loader. NOTE: ``train-fasttext`` IS a real task (has
# task.toml + instruction.md + environment + tests) — do NOT list it here.
_NON_TASK_ENTRIES: frozenset[str] = frozenset({
    "summary.json",
    "training_traces",
    "ia03_terminal_bench",
})

# Default wall-clock duration ranking source. ``tasks[].duration_sec`` gives
# the per-task single-run wall time (environment + agent + verifier); tasks
# without a measured duration keep ``rank: null`` and sort last. Generated by
# scanning harbor job result.json files — see
# terminalbench2/docs/task-duration-ranking.md.
DEFAULT_DURATION_JSON = os.path.expanduser(
    "~/work/terminalbench2/docs/task-duration-ranking.json"
)


def _looks_like_task_dir(task_path: str) -> bool:
    """A directory qualifies as a task iff it has ``task.toml`` + ``instruction.md``."""
    return (
        os.path.isfile(os.path.join(task_path, "task.toml"))
        and os.path.isfile(os.path.join(task_path, "instruction.md"))
    )


def _load_duration_map(duration_json: str) -> dict[str, float]:
    """Read ``duration_sorted.json`` → ``{task: duration_sec}``.

    Only entries with a real ``duration_sec`` (``rank`` not null) are kept;
    missing/unmeasured tasks simply won't be in the dict, so they fall back to
    :data:`_NO_DURATION` during sorting. Returns ``{}`` if the file is missing
    or malformed (logging a warning) so a broken duration file never blocks
    dataset loading.
    """
    if not os.path.isfile(duration_json):
        logger.warning(
            f"Duration ranking file not found: {duration_json}; skipping "
            f"duration-based sort (falling back to alpha order)"
        )
        return {}
    try:
        with open(duration_json, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        logger.warning(
            f"Failed to parse duration ranking {duration_json}: {e}; "
            f"falling back to alpha order"
        )
        return {}
    tasks = data.get("tasks", []) if isinstance(data, dict) else []
    duration_map: dict[str, float] = {}
    for entry in tasks:
        if not isinstance(entry, dict):
            continue
        # rank is null for unmeasured tasks — skip them so they sort last.
        if entry.get("rank") is None:
            continue
        name = entry.get("task")
        secs = entry.get("duration_sec")
        if isinstance(name, str) and isinstance(secs, (int, float)):
            duration_map[name] = float(secs)
    logger.info(
        f"Loaded duration ranking for {len(duration_map)} task(s) from "
        f"{duration_json}"
    )
    return duration_map


async def load_dataset(
    data_dir: str,
    max_samples: int = 0,
    shuffle: bool = False,
    allow_empty: bool = False,
    exclude: frozenset[str] | set[str] | None = None,
    duration_json: str | None = None,
    sort_by_duration: bool = False,
) -> list[TerminalBenchDataInst]:
    """Load a Terminal-Bench 2 dataset from a directory of task directories.

    Enumerates subdirectories of ``data_dir``, skips known non-task entries
    (``summary.json``, ``training_traces/``, etc.) and any task names in
    ``exclude``, and returns one :class:`TerminalBenchDataInst` per directory
    that has ``task.toml`` and ``instruction.md``.

    Args:
        data_dir: Terminal-Bench dataset root (e.g.
            ``~/work/terminalbench2/dataset``). Auto-opt points directly at
            the full ``dataset/`` and passes ``exclude`` to drop tasks that
            can't be solved offline — no separate ``dataset-training/`` split
            is maintained.
        max_samples: Maximum number of samples to load. 0 means load all.
        shuffle: Whether to shuffle the dataset before truncation. Mutually
            exclusive in spirit with ``sort_by_duration`` (shuffle wins if
            both are set).
        allow_empty: If ``True`` and ``data_dir`` contains no qualifying
            task directories, return an empty list instead of raising. Use
            this for optional splits such as a val set that may not have
            been populated yet (e.g. ``dataset-validation/`` is an empty
            dir in the shipping layout). The optimizer treats an empty val
            list as "skip validation" rather than an error.
        exclude: Optional set of task names to drop (after non-task
            filtering). Defaults to an empty set — every qualifying task
            directory is loaded. Pass a set of names to exclude specific
            tasks (e.g. ones that can't be solved under the offline harness).
        sort_by_duration: If ``True``, reorder tasks by ascending single-run
            wall-clock duration (fastest first) so early batches run the
            cheapest tasks. Tasks with no measured duration sort last,
            keeping their alpha relative order. Durations are read from
            ``duration_json`` (default :data:`DEFAULT_DURATION_JSON`).
            Applied *before* ``max_samples`` truncation, so a capped load
            takes the fastest N. Ignored when ``shuffle=True``.
        duration_json: Path to a ``duration_sorted.json`` (see
            :data:`DEFAULT_DURATION_JSON`). Defaults to that path when
            ``sort_by_duration=True``. Only consulted when
            ``sort_by_duration=True``.
    """
    if not os.path.isdir(data_dir):
        raise FileNotFoundError(f"Data directory not found: {data_dir}")

    excluded = frozenset(exclude) if exclude is not None else frozenset()

    task_names = sorted(
        entry
        for entry in os.listdir(data_dir)
        if entry not in _NON_TASK_ENTRIES
        and entry not in excluded
        and not entry.startswith(".")
        and os.path.isdir(os.path.join(data_dir, entry))
        and _looks_like_task_dir(os.path.join(data_dir, entry))
    )

    if not task_names:
        if allow_empty:
            logger.info(
                f"No task directories found in {data_dir}; returning empty "
                f"dataset (allow_empty=True)"
            )
            return []
        raise ValueError(f"No task directories found in {data_dir}")

    if excluded:
        logger.info(f"Excluding {len(excluded)} task(s) from {data_dir}: {sorted(excluded)}")

    # Reorder by measured wall-clock duration (fastest first) BEFORE any
    # truncation, so a capped load keeps the cheapest tasks. Unmeasured tasks
    # sink to the back; alpha order is preserved within a tie via stable sort.
    if sort_by_duration and not shuffle:
        json_path = duration_json or DEFAULT_DURATION_JSON
        duration_map = _load_duration_map(json_path)
        if duration_map:
            timed = [t for t in task_names if t in duration_map]
            untimed = [t for t in task_names if t not in duration_map]
            task_names = sorted(timed, key=lambda t: duration_map[t]) + untimed
            logger.info(
                f"Sorted {len(timed)} task(s) by duration "
                f"({len(untimed)} without measured data kept last)"
            )

    if shuffle:
        random.shuffle(task_names)

    if max_samples > 0:
        task_names = task_names[:max_samples]
    if max_samples == 0:
        return []

    result: list[TerminalBenchDataInst] = []
    for name in task_names:
        task_path = os.path.join(data_dir, name)
        try:
            result.append(TerminalBenchDataInst.from_task_dir(task_path))
        except Exception as e:
            logger.warning(f"Failed to load task {name}: {e}")
            continue

    logger.info(f"Loaded {len(result)} terminalbench tasks from {data_dir}")
    return result
